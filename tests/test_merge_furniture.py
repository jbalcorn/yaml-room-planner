import pytest
import yaml

from room_planner import merge_furniture


@pytest.fixture
def folder(tmp_path):
    return tmp_path


def write(folder, name, text, encoding="utf-8"):
    (folder / name).write_text(text, encoding=encoding)


def merged(folder):
    return yaml.safe_load((folder / "furniture.yaml").read_text(encoding="utf-8"))


def test_objects_from_all_files_are_merged(folder):
    write(folder, "furniture_a.yaml", "objects: {Sofa: {depth: 30}}")
    write(folder, "furniture_b.yaml", "objects: {Desk: {depth: 20}}")

    merge_furniture.merge_folder(folder)
    assert merged(folder)["objects"] == {"Sofa": {"depth": 30}, "Desk": {"depth": 20}}


def test_last_file_wins_for_objects_and_metadata(folder):
    write(folder, "furniture_b.yaml", "units: cm\nobjects: {Sofa: {depth: 34}}")
    write(folder, "furniture_a.yaml", "units: inches\nobjects: {Sofa: {depth: 30}}")

    merge_furniture.merge_folder(folder)

    assert merged(folder) == {"units": "cm", "objects": {"Sofa": {"depth": 34}}}


@pytest.mark.parametrize(("first", "second"), [("Sofa", "sofa"), ("sofa", "Sofa")])
def test_keys_match_across_files_ignoring_case(folder, first, second):
    write(folder, "furniture_a.yaml", f"Objects: {{{first}: {{depth: 30}}}}")
    write(folder, "furniture_b.yaml", f"objects: {{{second}: {{depth: 34}}}}")

    merge_furniture.merge_folder(folder)

    assert merged(folder)["objects"] == {first: {"depth": 34}}


def test_existing_output_is_not_used_as_input(folder):
    write(folder, "furniture.yaml", merge_furniture.HEADER + "objects: {Stale: {depth: 1}}")
    write(folder, "furniture_a.yaml", "objects: {Sofa: {depth: 30}}")

    merge_furniture.merge_folder(folder)

    assert list(merged(folder)["objects"]) == ["Sofa"]


def test_unrelated_files_are_ignored(folder):
    write(folder, "furniture_a.yaml", "objects: {Sofa: {depth: 30}}")
    write(folder, "layout.yaml", "objects: {Other: {depth: 1}}")

    merge_furniture.merge_folder(folder)

    assert list(merged(folder)["objects"]) == ["Sofa"]


@pytest.mark.parametrize("text", ["", "# only a comment\n", "objects:\n"])
def test_files_without_objects_are_allowed(folder, text):
    write(folder, "furniture_a.yaml", text)

    merge_furniture.merge_folder(folder)
    assert merged(folder) == {"objects": {}}


def test_byte_order_mark_is_accepted(folder):
    write(folder, "furniture_a.yaml", "units: inches", encoding="utf-8-sig")

    merge_furniture.merge_folder(folder)

    assert merged(folder)["units"] == "inches"


def test_warning_header_is_written_once(folder):
    write(folder, "furniture_a.yaml", "units: inches")

    merge_furniture.merge_folder(folder)
    merge_furniture.merge_folder(folder)

    text = (folder / "furniture.yaml").read_text(encoding="utf-8")
    assert text.startswith("# DO NOT EDIT THIS FILE DIRECTLY.")
    assert text.count("DO NOT EDIT") == 1


def test_sources_are_found_in_name_order(folder):
    write(folder, "furniture_b.yaml", "units: inches")
    write(folder, "furniture_a.yaml", "units: inches")

    names = [path.name for path in merge_furniture.find_sources(folder)]
    assert names == ["furniture_a.yaml", "furniture_b.yaml"]


def test_no_sources_is_an_error(folder):
    with pytest.raises(FileNotFoundError, match="No furniture_"):
        merge_furniture.merge_folder(folder)


def test_hand_written_output_is_not_overwritten(folder):
    write(folder, "furniture.yaml", "objects: {Mine: {depth: 1}}")
    write(folder, "furniture_a.yaml", "objects: {Sofa: {depth: 30}}")

    with pytest.raises(ValueError, match="merge --force"):
        merge_furniture.merge_folder(folder)
    assert list(merged(folder)["objects"]) == ["Mine"]

    merge_furniture.merge_folder(folder, force=True)
    assert list(merged(folder)["objects"]) == ["Sofa"]


@pytest.mark.parametrize(
    ("text", "message"),
    [
        ("objects: {A: 1, A: 2}", "duplicate key"),
        ("objects: [unclosed", "Could not parse .*furniture_bad.yaml"),
        ("- a\n- b\n", "expected a mapping"),
        ("objects: [a]", "'objects' must be a mapping"),
    ],
)
def test_bad_input_stops_and_keeps_existing_output(folder, text, message):
    existing = merge_furniture.HEADER + "units: keep me"
    write(folder, "furniture.yaml", existing)
    write(folder, "furniture_bad.yaml", text)

    with pytest.raises(ValueError, match=message):
        merge_furniture.merge_folder(folder)

    assert (folder / "furniture.yaml").read_text(encoding="utf-8") == existing
