#!/usr/bin/env python3
"""Merge every furniture*.yaml in the current directory into furniture.yaml.

Python port of Get-Furniture.ps1. Files are merged in name order; when a key
appears in more than one file, the last file wins. Keys match case-insensitively
across files, as they do in a PowerShell hashtable.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError as exc:
    raise SystemExit("PyYAML is required: pip install PyYAML") from exc

OUTPUT_NAME = "furniture.yaml"
HEADER = """# DO NOT EDIT THIS FILE DIRECTLY.
# It is generated by get_furniture.py, and any changes will be overwritten.
# Edit the furniture_*.yaml files instead, then run get_furniture.py.
"""


class UniqueKeyLoader(yaml.SafeLoader):
    """SafeLoader that rejects duplicate keys instead of keeping the last one."""

    def construct_mapping(self, node, deep=False):
        seen = set()
        for key_node, _ in node.value:
            if key_node.tag == "tag:yaml.org,2002:merge":
                continue
            key = self.construct_object(key_node, deep=True)
            if key in seen:
                raise yaml.constructor.ConstructorError(
                    None, None, f"duplicate key: {key!r}", key_node.start_mark
                )
            seen.add(key)
        return super().construct_mapping(node, deep)


def put(target: dict, key: Any, value: Any) -> None:
    """Set target[key], reusing an existing key that differs only by case."""
    folded = str(key).lower()
    key = next((k for k in target if str(k).lower() == folded), key)
    target[key] = value


def main() -> int:
    folder = Path.cwd()
    output = folder / OUTPUT_NAME
    sources = sorted(
        (
            p
            for p in folder.glob("furniture*.yaml")
            if p.is_file() and p.name.lower() != OUTPUT_NAME
        ),
        key=lambda p: p.name.lower(),
    )

    merged: dict = {"objects": {}}
    for path in sources:
        print(path)
        try:
            # utf-8-sig accepts files with or without a byte order mark.
            content = yaml.load(path.read_text(encoding="utf-8-sig"), UniqueKeyLoader)
        except yaml.YAMLError as exc:
            raise SystemExit(f"Could not parse {path.name}: {exc}") from exc
        if not content:
            continue
        if not isinstance(content, dict):
            raise SystemExit(f"{path.name}: expected a mapping at the top level")

        for key, value in content.items():
            if str(key).lower() != "objects":
                put(merged, key, value)
                continue
            for name, item in (value or {}).items():
                put(merged["objects"], name, item)

    # Put the metadata (version, units, ...) ahead of the objects.
    merged["objects"] = merged.pop("objects")
    output.write_text(
        HEADER + yaml.safe_dump(merged, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
